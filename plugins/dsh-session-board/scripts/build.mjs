/**
 * Build both halves.
 *
 *   src/index.ts        -> lib/index.js    (host: self-contained ESM with Node builtins external)
 *   src/client/index.tsx -> lib/client.js  (browser: CJS wrapped in the
 *                                           `window.__ModuleLoader__.load` envelope
 *                                           the client module system expects)
 *
 * The client bundle resolves `react` and `react-dom/client` from the shell's
 * frozen module table, which is the documented baseline for a client plugin.
 * Anything outside that table would have to be declared under
 * `dsh.client.external`; this plugin deliberately needs nothing else, so the
 * list below is exactly the platform baseline.
 *
 * esbuild is a build-time tool only. It is resolved from this package first,
 * then from a DSH source checkout, then from PATH, so the script works in a
 * bare workspace without installing anything.
 */
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const lib = process.env.DSH_BOARD_OUTPUT ? join(root, process.env.DSH_BOARD_OUTPUT) : join(root, 'lib')
const PLUGIN_ID = 'dsh-session-board'

/** The shell's frozen module table: the only externals a client bundle may use. */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

/**
 * Host-side externals: none.
 *
 * The host bundle must carry everything it needs. Node resolves a plugin's bare
 * imports from the plugin's own directory, and the `@deepseek-ai/*` packages are
 * deliberately not installed into the profile, so a runtime import of one makes
 * the plugin fail to load. `node:` builtins stay external automatically under
 * `--platform=node`.
 */
const HOST_EXTERNALS = []

/** Locate an esbuild binary without assuming a local install. */
function resolveEsbuild() {
  const candidates = [
    process.env.ESBUILD_BINARY,
    join(root, 'node_modules', '.bin', 'esbuild'),
    process.env.DSH_REPO === undefined ? undefined : join(process.env.DSH_REPO, 'node_modules', '.bin', 'esbuild'),
    join(root, '..', '..', '..', 'deepseek-harness', 'node_modules', '.bin', 'esbuild'),
  ].filter((value) => typeof value === 'string')
  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate
  }
  return 'esbuild'
}

/** Run one esbuild invocation, inheriting stdio so diagnostics reach the caller. */
function run(binary, args) {
  const result = spawnSync(binary, args, { cwd: root, stdio: 'inherit' })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) process.exit(result.status ?? 1)
}

/** Build the host half. */
function buildHost(binary) {
  run(binary, [
    'src/index.ts',
    '--bundle',
    '--format=esm',
    '--platform=node',
    '--target=node22',
    `--outfile=${join(lib, 'index.js.tmp')}`,
    ...HOST_EXTERNALS.map((name) => `--external:${name}`),
  ])
}

/** Build the browser half, then wrap it in the module-loader envelope. */
function buildClient(binary) {
  mkdirSync(lib, { recursive: true })
  const raw = join(lib, 'client.raw.cjs')
  run(binary, [
    'src/client/index.tsx',
    '--bundle',
    '--format=cjs',
    '--platform=browser',
    '--target=es2022',
    '--jsx=automatic',
    '--minify-syntax',
    `--outfile=${raw}`,
    ...PLATFORM_MODULES.map((name) => `--external:${name}`),
  ])

  const body = readFileSync(raw, 'utf8')
  // esbuild's CJS output assigns `module.exports` and never touches a bare
  // `exports`, so the envelope only needs to provide `module`.
  const banner = `/* Generated by scripts/build.mjs from src/client — edit the source, not this file. */\n`
    + `window.__ModuleLoader__.load({\n  id: ${JSON.stringify(PLUGIN_ID)},\n  factory: (require) => {\n`
    + `    var module = { exports: {} };\n`
  const footer = `\n    return module.exports;\n  }\n});\n`

  // Write via a temp file plus rename so a concurrent read never sees a
  // truncated bundle.
  const target = join(lib, 'client.js')
  const temporary = join(lib, 'client.js.tmp')
  writeFileSync(temporary, banner + body + footer)
  renameSync(temporary, target)
  rmSync(raw, { force: true })
}

// Strict checking catches undefined runtime references before any bundle is replaced.
run(process.execPath, [join(root, 'scripts/typecheck.mjs')])
run(process.execPath, [join(root, 'scripts/typecheck.mjs'), '--declarations'])
const binary = resolveEsbuild()
mkdirSync(lib, { recursive: true })
rmSync(join(lib, 'client.js.tmp'), { force: true })
buildHost(binary)
writeFileSync(join(lib, 'index.d.ts'), "/** Generated facade. */\nexport * from './types/index.js'\n")
buildClient(binary)
copyFileSync(join(root, 'src/host/wiki-workflow.py'), join(lib, 'wiki-workflow.py'))
renameSync(join(lib, 'index.js.tmp'), join(lib, 'index.js'))
process.stdout.write(`dsh-session-board: built lib/index.js and lib/client.js with ${binary}\n`)
