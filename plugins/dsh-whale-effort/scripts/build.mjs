/**
 * Build both halves of dsh-whale-effort.
 *
 *   src/index.ts          -> lib/index.js   (host: self-contained ESM, Node builtins external)
 *   src/client/index.tsx  -> lib/client.js  (browser: CJS wrapped in the
 *                                            `window.__ModuleLoader__.load` envelope)
 *
 * The client bundle resolves the shell's frozen module table (react and the
 * documented @deepseek-ai client packages) at runtime; everything else — the
 * chibi sprite strip, the agent tutorial Markdown and every style string — is
 * inlined, so the published package is a single self-contained client file.
 *
 * esbuild is a build-time tool only. It is resolved from this package first,
 * then from a DSH source checkout, then from PATH, so the script works in a
 * bare workspace without installing anything.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const lib = join(root, 'lib')
const PLUGIN_ID = 'dsh-whale-effort'

/** The shell's frozen module table: the only externals a client bundle may use. */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

/** Locate an esbuild binary without assuming a local install. */
function resolveEsbuild() {
  const candidates = [
    process.env.ESBUILD_BINARY,
    join(root, 'node_modules', '.bin', 'esbuild'),
    process.env.DSH_REPO === undefined ? undefined : join(process.env.DSH_REPO, 'node_modules', '.bin', 'esbuild'),
    join(root, '..', '..', '..', 'deepseek-harness', 'node_modules', '.bin', 'esbuild'),
  ].filter((value) => typeof value === 'string')
  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate
  }
  return 'esbuild'
}

/** Run one build step and fail the whole build when it fails. */
function run(binary, args) {
  const result = spawnSync(binary, args, { cwd: root, stdio: 'inherit' })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) process.exit(result.status ?? 1)
}

/** Build the host half as one bundled ESM file. */
function buildHost(binary) {
  run(binary, [
    'src/index.ts',
    '--bundle',
    '--format=esm',
    '--platform=node',
    '--target=node22',
    '--legal-comments=none',
    `--outfile=${join(lib, 'index.js.tmp')}`,
  ])
  renameSync(join(lib, 'index.js.tmp'), join(lib, 'index.js'))
}

/** Build the browser half, then wrap it in the module-loader envelope. */
function buildClient(binary) {
  const raw = join(lib, 'client.raw.cjs')
  run(binary, [
    'src/client/index.tsx',
    '--bundle',
    '--format=cjs',
    '--platform=browser',
    '--target=es2022',
    '--jsx=automatic',
    '--minify-syntax',
    '--legal-comments=none',
    '--loader:.png=dataurl',
    '--loader:.md=text',
    `--outfile=${raw}`,
    ...PLATFORM_MODULES.map((name) => `--external:${name}`),
  ])

  const body = readFileSync(raw, 'utf8')
  // esbuild's CJS output assigns `module.exports` and never touches a bare
  // `exports`, so the envelope only needs to provide `module`.
  const banner = '/* Generated by scripts/build.mjs from src/client — edit the source, not this file. */\n'
    + `window.__ModuleLoader__.load({\n  id: ${JSON.stringify(PLUGIN_ID)},\n  factory: (require) => {\n`
    + '    var module = { exports: {} };\n'
  const footer = '\n    return module.exports;\n  }\n});\n'

  // Write through a temp file plus rename so a concurrent read never sees a
  // truncated bundle.
  const target = join(lib, 'client.js')
  const temporary = join(lib, 'client.js.tmp')
  writeFileSync(temporary, banner + body + footer)
  renameSync(temporary, target)
  rmSync(raw, { force: true })
}

mkdirSync(lib, { recursive: true })
// Strict checking runs before any artifact is replaced.
run(process.execPath, [join(root, 'scripts/typecheck.mjs')])
run(process.execPath, [join(root, 'scripts/typecheck.mjs'), '--declarations'])
const binary = resolveEsbuild()
buildHost(binary)
writeFileSync(join(lib, 'index.d.ts'), "/** Generated facade. */\nexport * from './types/index.js'\n")
buildClient(binary)
process.stdout.write(`dsh-whale-effort: built lib/index.js and lib/client.js with ${binary}\n`)
