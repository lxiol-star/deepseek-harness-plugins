/**
 * Build the browser half: `src/client.js` → `lib/client.js`.
 *
 * The source is a set of ES modules (`src/client.js`, `src/client/**`,
 * `src/canvas/**`). esbuild bundles them into one CommonJS file, which is then
 * wrapped in the `window.__ModuleLoader__.load` envelope the client module
 * system expects:
 *
 *   window.__ModuleLoader__.load({
 *     id: 'dsh-kimi-tower',
 *     factory(require) { … return module.exports … },
 *   })
 *
 * The bundle resolves `react` and `react-dom` from the shell's frozen module
 * table, which is the documented baseline for a client plugin. Those two are
 * the only externals, and the build fails if the bundle asks `require` for
 * anything else — nothing under `@deepseek-ai/*` may reach the browser half.
 *
 * esbuild is a build-time tool only and never ends up in the bundle.
 */
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const PLUGIN_ID = 'dsh-kimi-tower'

/** The shell's frozen module table: the only externals a client bundle may use. */
export const CLIENT_EXTERNALS = Object.freeze(['react', 'react-dom'])

/** Every `require(…)` the bundle issues. */
const REQUIRE = /\brequire\((["'])([^"']+)\1\)/g

/**
 * List the modules a bundle asks the loader for.
 *
 * @param code - the bundled JavaScript.
 * @returns the module names, sorted and without repeats.
 */
export function requiredModules(code) {
  return [...new Set([...String(code).matchAll(REQUIRE)].map(match => match[2]))].sort()
}

/**
 * Wrap a CommonJS bundle in the module-loader envelope.
 *
 * @param body - the bundle.
 * @returns the contents of `lib/client.js`.
 */
export function wrapClient(body) {
  return `/* Generated by scripts/build-client.mjs from src/client.js — edit the source, not this file. */\n`
    + `window.__ModuleLoader__.load({\n  id: '${PLUGIN_ID}',\n  factory(require) {\n`
    // esbuild's CommonJS output works through `module.exports`; `exports` is
    // provided too, in case a future module references it directly.
    + `    var module = { exports: {} };\n    var exports = module.exports;\n`
    + body
    + `\n    return module.exports;\n  }\n})\n`
}

/**
 * Build `lib/client.js`.
 *
 * @param options - `{ lib, logLevel }`; `lib` defaults to the package's `lib`.
 * @returns `{ file, bytes }`.
 */
export async function buildClient(options = {}) {
  const lib = options.lib ?? join(root, 'lib')
  // esbuild's own summary is replaced by the one line this build prints.
  const logLevel = options.logLevel ?? 'warning'
  mkdirSync(lib, { recursive: true })
  const raw = join(lib, 'client.raw.cjs')

  await build({
    absWorkingDir: root,
    entryPoints: ['src/client.js'],
    outfile: raw,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    external: [...CLIENT_EXTERNALS],
    minifySyntax: true,
    legalComments: 'none',
    logLevel,
  })

  const body = readFileSync(raw, 'utf8')
  rmSync(raw, { force: true })
  const modules = requiredModules(body)
  const unexpected = modules.filter(name => !CLIENT_EXTERNALS.includes(name))
  if (unexpected.length > 0) {
    throw new Error(`lib/client.js would require modules outside the platform baseline: ${unexpected.join(', ')}`)
  }

  // Write via a temp file plus rename so a concurrent read never sees a
  // truncated bundle.
  const target = join(lib, 'client.js')
  const temporary = join(lib, 'client.js.tmp')
  const code = wrapClient(body)
  writeFileSync(temporary, code)
  renameSync(temporary, target)
  return { file: target, bytes: Buffer.byteLength(code), modules }
}

// Run as a script (`node scripts/build-client.mjs`); a no-op when imported.
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildClient()
  console.log(`  lib/client.js  built (${result.bytes} bytes; requires ${result.modules.join(', ')})`)
}
