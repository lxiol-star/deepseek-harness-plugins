/**
 * The browser half as it ships: the single-file `lib/client.js`, and the pure
 * modules behind the canvas view.
 *
 * The repository deliberately does not depend on React, so nothing here
 * renders. What is pinned instead:
 *
 *  - `lib/client.js` is the file `scripts/build.mjs` generates from the
 *    sources, byte for byte, wrapped in the module-loader envelope;
 *  - its `require` only ever asks for the platform baseline (`react`,
 *    `react-dom`);
 *  - `apply(ctx)` registers the three slot contributions with the ids the
 *    shell expects, with a stub `react` and a stub document;
 *  - nothing in the sources or the bundle writes markup;
 *  - the pieces the overlay leans on: text sanitising, wire geometry, what
 *    stays highlighted on selection, the shared store, and the status reads.
 */
