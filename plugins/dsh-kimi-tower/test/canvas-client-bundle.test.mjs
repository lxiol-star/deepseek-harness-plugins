test('wireGeometry draws the line short of its arrowhead, which ends exactly at the last point', () => {
  assert.deepEqual(wireGeometry([[0, 0], [100, 0]]), { path: 'M0 0L91 0', head: 'M100 0L91 5L91 -5Z' })
  assert.deepEqual(wireGeometry([[0, 0], [0, 10]]), { path: 'M0 0L0 1', head: 'M0 10L-5 1L5 1Z' })
  // A diagonal last leg: the head follows its direction.
  const diagonal = wireGeometry([[0, 0], [50, 0], [50, 50], [100, 100]])
  assert.equal(diagonal.path, 'M0 0L50 0L50 50L93.64 93.64')
  // Coordinates are rounded to a hundredth, and the head is symmetrical about the wire.
  const [[hx, hy], [b1x, b1y], [b2x, b2y]] = diagonal.head.slice(1, -1).split('L').map(point => point.split(' ').map(Number))
  // The head is a thin isosceles triangle: both base corners as far from the tip, a base as wide as two half-widths.
  const near = (a, b) => Math.abs(a - b) < 0.02
  assert.ok(near(Math.hypot(hx - b1x, hy - b1y), Math.hypot(hx - b2x, hy - b2y)), 'symmetrical about the wire')
  assert.ok(near(Math.hypot(b1x - b2x, b1y - b2y), HEAD_HALF * 2), 'as wide as it was drawn to be')
})

test('wireGeometry survives a last leg shorter than its head, a lone point and a repeated point', () => {
  const short = wireGeometry([[0, 0], [4, 0]])
  assert.equal(short.path, 'M0 0L0 0')
  assert.equal(short.head, 'M4 0L0 2.22L0 -2.22Z', 'the head shrinks to the leg rather than poking out backwards')
  for (const points of [[[3, 4]], [[5, 5], [5, 5]], [[0, 0], [1e-7, 0], [0, 0]]]) {
    const geometry = wireGeometry(points)
    assert.ok(!/NaN|Infinity/.test(geometry.path + geometry.head), JSON.stringify(points))
  }
  assert.equal(HEAD, 9)
  assert.equal(HEAD_HALF, 5)
})

test('wireDirection names where a wire points', () => {
  assert.equal(wireDirection([[0, 0], [10, 2]]), '右')
  assert.equal(wireDirection([[10, 0], [0, 2]]), '左')
  assert.equal(wireDirection([[0, 0], [2, 10]]), '下')
  assert.equal(wireDirection([[0, 10], [2, 0]]), '上')
})

