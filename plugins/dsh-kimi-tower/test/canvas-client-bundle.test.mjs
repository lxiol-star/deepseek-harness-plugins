test('sanitizeText keeps emoji, combining marks and every script intact', () => {
  const text = '中文 English 日本語 العربية עברית 👨‍👩‍👧‍👦 👍🏽 🇨🇳 ❤️ e\u0301 Café .tower/worktrees/wt-4 — ok'
  assert.equal(sanitizeText(text), text)
  assert.equal(sanitizeText('a\u00a0b'), 'a b', 'a no-break space is whitespace')
  assert.equal(sanitizeText('a\u200bb'), 'a\u200bb', 'a zero-width space is not in the list and is left alone')
})

test('sanitizeText strips the bidi and control characters the tower listed', () => {
  const listed = [
    '\u202a', '\u202b', '\u202c', '\u202d', '\u202e', // embeddings, overrides, pop
    '\u2066', '\u2067', '\u2068', '\u2069', // isolates
    '\u200e', '\u200f', '\u061c', // LRM, RLM, ALM
    '\u0085', // NEL
    '\u001c', '\u001d', '\u001e', '\u001f', '\u001b', // information separators, ESC
    '\u0000', // NUL
    '\u0001', '\u0007', '\u007f', '\u009b', // and the rest of C0 / C1
  ]
  for (const character of listed) {
    assert.equal(sanitizeText(`a${character}b`), 'ab', `U+${character.codePointAt(0).toString(16)}`)
  }
  // The classic spoof: an override makes the tail read backwards.
  assert.equal(sanitizeText('任务 M4 状态: done\u202E ;derongi si noT'), '任务 M4 状态: done ;derongi si noT')
  // The zero-width joiner that holds an emoji sequence together is not a control character here.
  assert.equal(sanitizeText('👨\u200d👩'), '👨\u200d👩')
})

test('sanitizeText folds whitespace, trims the ends and maps non-strings to an empty string', () => {
  assert.equal(sanitizeText('  a \t\n b   c\u00a0d\u3000e\u2028f '), 'a b c d e f')
  assert.equal(sanitizeText('\n\n'), '')
  for (const value of [undefined, null, 0, 42, true, {}, [], Symbol('x')]) assert.equal(sanitizeText(value), '')
})

/** Every string anywhere inside a value. */
function stringsIn(value, found = []) {
  if (typeof value === 'string') found.push(value)
  else if (Array.isArray(value)) value.forEach(item => stringsIn(item, found))
  else if (value !== null && typeof value === 'object') Object.values(value).forEach(item => stringsIn(item, found))
  return found
}

