const root = new URL('..', import.meta.url).pathname

/** Read a file of this package. */
const read = path => readFile(join(root, path), 'utf8')

/** A value as plain data, so that an array or object made inside the vm context compares equal to one made here. */
const plain = value => JSON.parse(JSON.stringify(value))

/** Every file below a directory of this package, recursively. */
async function filesBelow(path) {
  const entries = await readdir(join(root, path), { withFileTypes: true })
  const files = await Promise.all(entries.map(entry => (entry.isDirectory()
    ? filesBelow(`${path}/${entry.name}`)
    : `${path}/${entry.name}`)))
  return files.flat()
}

/** Mark-up sinks that must never appear in the browser half. */
const MARKUP_SINKS = ['dangerouslySetInnerHTML', 'innerHTML', 'insertAdjacentHTML', 'outerHTML', 'foreignObject', 'document.write', 'file://']

