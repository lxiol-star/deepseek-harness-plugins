  const bundle = await read('lib/client.js')
  assert.match(bundle, /^\/\* Generated by scripts\/build-client\.mjs from src\/client\.js[^\n]*\*\/\nwindow\.__ModuleLoader__\.load\(\{\n  id: 'dsh-kimi-tower',\n  factory\(require\) \{\n    var module = \{ exports: \{\} \};\n    var exports = module\.exports;\n/)
  assert.ok(bundle.endsWith('\n    return module.exports;\n  }\n})\n'), 'the factory returns its module')
