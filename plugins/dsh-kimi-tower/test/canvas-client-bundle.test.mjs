test('every canvas entry shares one open state, and the dock feeds the header toggle', async () => {
  const { slots } = await loadClient()
  const store = slots.get('conversation.session.header.actions')[0].options.inject().store
  const dockFace = slots.get('conversation.input.dock')[0].options.inject()
  const seen = []
  const unsubscribe = store.subscribe(() => seen.push([store.isOpen(), store.openedFor()]))

  // A tower that is off, or that belongs to another session, keeps the toggle hidden.
  dockFace.reportTower('session-1', null)
  dockFace.reportTower('session-1', { active: false, running: 0, missions: [] })
  dockFace.reportTower('session-1', { active: true, sessionId: 'session-2', missions: [] })
  assert.deepEqual(plain(store.towerOf('session-1')), { sessionId: 'session-1', active: false, missions: 0 })
  dockFace.reportTower('session-1', { active: true, sessionId: 'session-1', running: 0, missions: [] })
  assert.deepEqual(plain(store.towerOf('session-1')), { sessionId: 'session-1', active: true, missions: 0 }, 'on, with no mission')

  // Both entries open the same canvas for the session they belong to.
  dockFace.openCanvas('session-1')
  assert.deepEqual(plain(seen.at(-1)), [true, 'session-1'])
  store.close()
  store.open('session-1')
  assert.equal(store.isOpen(), true)
  const heard = seen.length
  unsubscribe()
  store.close()
  assert.equal(seen.length, heard, 'a listener that left is not called')
})

