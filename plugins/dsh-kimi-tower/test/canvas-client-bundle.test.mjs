  assert.equal(/\bimport\s*\(/.test(bundle), false, 'no dynamic import: the loader hands over one file')
  // What the loader is asked for is the platform baseline, and nothing else.
  assert.deepEqual(requiredModules(bundle), [...CLIENT_EXTERNALS])
